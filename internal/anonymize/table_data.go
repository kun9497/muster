// TableVersion names this classification; Task 6 records it beside the
// scheme. A row that changes a value's class changes it.
const TableVersion = "v1"

// The row shorthands of Default. A structural row (rNode, a list's row) has no
// value class: what lies under it is classified by its own rows.
