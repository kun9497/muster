package main

import (
	"fmt"
	"sort"
	"strings"

	"github.com/kun9497/muster/internal/controls"
)

const header = "<!-- Generated by go run ./tools/coverage; do not edit. -->\n"

// join matches the inventory against the control set. byItem holds the
// controls claiming each item; stage holds, for each deferred item, the
// stage it is deferred to; unknown holds the rendered rows for references to
// items that are not in the inventory at all.
func join(items []controls.KISAItem, deferred []controls.Deferral, set []controls.Control) (byItem map[string][]controls.Control, stage map[string]string, unknown []string) {
	known := map[string]bool{}
	for _, it := range items {
		known[it.ID] = true
	}
	byItem = map[string][]controls.Control{}
	for _, c := range set {
		for _, id := range c.References.KISA[controls.LatestKISAEdition] {
			if !known[id] {
				unknown = append(unknown, fmt.Sprintf("| %s | %s | unknown item |", c.ID, id))
				continue
			}
			byItem[id] = append(byItem[id], c)
		}
	}
	stage = map[string]string{}
	for _, d := range deferred {
		stage[d.ID] = d.Stage
	}
	return byItem, stage, unknown
}

// countEnrolled is how many inventory items muster judges today, over an
// already-joined set. A deferred item never counts, whatever the set says:
// the deferral file is the statement of intent, and an item both deferred
// and claimed is a lint failure (kisa_coverage), not a coverage gain.
func countEnrolled(items []controls.KISAItem, byItem map[string][]controls.Control, stage map[string]string) int {
	n := 0
	for _, it := range items {
		if _, isDeferred := stage[it.ID]; isDeferred {
			continue
		}
		if len(byItem[it.ID]) > 0 {
			n++
		}
	}
	return n
}

// countAutomation counts the ENROLLED controls by automation kind, the same
// way countEnrolled counts items: a deferred item contributes nothing, and a
// control no inventory item names is not enrolled. The table's summary line
// and the README guard both read it, so the parenthetical in the READMEs can
// never drift from the one in coverage.md (M-3, G-2).
func countAutomation(items []controls.KISAItem, byItem map[string][]controls.Control, stage map[string]string) (auto, partial, manual int) {
	for _, it := range items {
		if _, isDeferred := stage[it.ID]; isDeferred {
			continue
		}
		for _, c := range byItem[it.ID] {
			switch c.Automation {
			case "auto":
				auto++
			case "partial":
				partial++
			case "manual":
				manual++
			}
		}
	}
	return auto, partial, manual
}

// coverageNumbers are the numbers both READMEs and the table's summary line
// state: how many of the inventory's items the set enrols, how many items
// there are, and how the enrolled controls divide by automation.
type coverageNumbers struct{ enrolled, total, auto, partial, manual int }

// counts answers all of them from the inputs, for callers that have not
// joined anything -- the README guard in main.go. The table and the guard
// therefore share one definition of "enrolled" and one of the triple.
func counts(items []controls.KISAItem, deferred []controls.Deferral, set []controls.Control) coverageNumbers {
	byItem, stage, _ := join(items, deferred, set)
	auto, partial, manual := countAutomation(items, byItem, stage)
	return coverageNumbers{enrolled: countEnrolled(items, byItem, stage), total: len(items), auto: auto, partial: partial, manual: manual}
}

// render joins the KISA inventory with the embedded control set and appends
// the fact-key report. One row per item in id order; an item deferred to a
// later stage says so and names the stage; a control citing an item that is
// not in the inventory is listed separately so a typo in references.kisa is
// visible.
func render(items []controls.KISAItem, deferred []controls.Deferral, usage []controls.CollectorUsage, set []controls.Control) string {
	byItem, stage, unknown := join(items, deferred, set)
	sorted := append([]controls.KISAItem(nil), items...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].ID < sorted[j].ID })
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("# KISA 2026 Unix items — coverage\n\n")
	var rows []string
	for _, it := range sorted {
		if st, isDeferred := stage[it.ID]; isDeferred {
			rows = append(rows, fmt.Sprintf("| %s | %s | %s | — | — | deferred (stage %s) |", it.ID, it.NameKo, it.Importance, st))
			continue
		}
		cs := byItem[it.ID]
		if len(cs) == 0 {
			rows = append(rows, fmt.Sprintf("| %s | %s | %s | — | — | not enrolled |", it.ID, it.NameKo, it.Importance))
			continue
		}
		sort.Slice(cs, func(i, j int) bool { return cs[i].ID < cs[j].ID })
		for _, c := range cs {
			rows = append(rows, fmt.Sprintf("| %s | %s | %s | %s | %s | enrolled |", it.ID, it.NameKo, it.Importance, c.ID, c.Automation))
		}
	}
	auto, partial, manual := countAutomation(items, byItem, stage)
	fmt.Fprintf(&b, "%d of %d items enrolled (auto %d, partial %d, manual %d).\n\n",
		countEnrolled(items, byItem, stage), len(sorted), auto, partial, manual)
	b.WriteString("| ID | Item (KISA) | Imp. | Control | Automation | Status |\n|---|---|---|---|---|---|\n")
	b.WriteString(strings.Join(rows, "\n"))
	b.WriteString("\n")
	if len(unknown) > 0 {
		sort.Strings(unknown)
		b.WriteString("\n## References to unknown items\n\n| Control | Reference | Status |\n|---|---|---|\n")
		b.WriteString(strings.Join(unknown, "\n"))
		b.WriteString("\n")
	}
	b.WriteString(renderUsage(usage))
	return b.String()
}

// renderUsage is spec §11 as a table: facts used, not facts collected. One
// row per collector in the order FactUsage reports them, and a summary line
// whose three numbers account for every registered key. A collector that has
// no unused key gets an em dash rather than an empty cell.
func renderUsage(usage []controls.CollectorUsage) string {
	// The same three numbers the lint note states, from the same fold.
	registered, used, engine := controls.Totals(usage)
	unused := registered - used - engine
	var b strings.Builder
	b.WriteString("\n## Fact keys used by controls\n\n")
	fmt.Fprintf(&b, "%d of %d registered keys are read by a control (%d by the engine); %d unused.\n\n", used, registered, engine, unused)
	b.WriteString("| Collector | Registered | Used by a control | Read by the engine | Unused |\n|---|---|---|---|---|\n")
	for _, u := range usage {
		cell := "—"
		if len(u.Unused) > 0 {
			cell = strings.Join(u.Unused, ", ")
		}
		fmt.Fprintf(&b, "| %s | %d | %d | %d | %s |\n", u.Collector, u.Registered, u.Used, u.Engine, cell)
	}
	return b.String()
}
