func TestRenderCISColumnAndBenchmarkLines(t *testing.T) {
	items := []controls.KISAItem{{ID: "U-01", NameKo: "x", Importance: "상"}}
	set := []controls.Control{
		{ID: "muster.a", Automation: "auto", References: controls.References{KISA: map[string][]string{"2026": {"U-01"}}}},
		{ID: "muster.beyond.b", Category: "beyond", Importance: "중", Automation: "auto"},
		{ID: "muster.beyond.c", Category: "beyond", Importance: "중", Automation: "auto"},
	}
	// muster.a is in the index fixture as "muster.a"; use real ids there.
	ixs := cisFixture()
	for _, ix := range ixs {
		for i := range ix.Recs {
			for j, c := range ix.Recs[i].Controls {
				switch c {
				case "muster.a":
					ix.Recs[i].Controls[j] = "muster.a"
				case "muster.b":
					ix.Recs[i].Controls[j] = "muster.beyond.b"
				}
			}
		}
	}
	got := render(items, nil, nil, set, ixs)
	for _, want := range []string{
		"| U-01 | x | 상 | muster.a | auto | rhel9 1.1.1 (none); ubuntu2204 5.2.9 (none), 5.2.10 (some), 5.10.2 | enrolled |",
		"| muster.beyond.b | 중 | auto | — | — | ubuntu2204 5.2.10 (some) |",
		"| muster.beyond.c | 중 | auto | — | — | — |",
		"\n## CIS Benchmarks\n\n" + cisMapNote + "\n\n- ",
		"The counts below and the CIS recs cells cover muster's map of controls to recommendations (`docs/reference/cis/map.yaml`); each `cis-<product>-l1` profile drops the controls `docs/reference/cis/review.yaml` names.",
		"2 controls map 2 of 9 Level 1 – Server recommendations (CIS Ubuntu Linux 22.04 LTS Benchmark v2.0.0, via ComplianceAsCode v0.1.82)",
		"1 controls map 1 of 4 Level 1 – Server recommendations (CIS Red Hat Enterprise Linux 9 Benchmark v2.0.0, via ComplianceAsCode v0.1.83)",
		"On AlmaLinux and Rocky hosts the profile carries RHEL 9's coverage words and parameter values.",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %q in:\n%s", want, got)
		}
	}
	if strings.Index(got, "CIS Red Hat") > strings.Index(got, "CIS Ubuntu") {
		t.Errorf("rhel9 sorts before ubuntu2204:\n%s", got)
	}
	if i := strings.Index(got, "## CIS Benchmarks"); i < 0 || strings.Contains(got[i:], "%") {
		t.Errorf("the CIS section must carry no percentage")
	}
	if strings.Contains(got, "%") {
		t.Errorf("no percent sign anywhere")
	}
	if render(items, nil, nil, set, ixs) != got {
		t.Error("render must be deterministic")
	}
}

