// M-1/M-2: an item muster defers to a later stage is not a gap in the table
// and not an enrolment either. It says so, names the stage, and stays out of
// the enrolled count so the summary line keeps meaning "judged today".
func TestRenderMarksDeferredItems(t *testing.T) {
	items := []controls.KISAItem{
		{ID: "U-01", NameKo: "root 계정 원격 접속 제한", Importance: "상"},
		{ID: "U-15", NameKo: "파일 및 디렉터리 소유자 설정", Importance: "상"},
		{ID: "U-33", NameKo: "숨겨진 파일 및 디렉토리 검색 및 제거", Importance: "하"},
		{ID: "U-45", NameKo: "메일 서비스 버전 점검", Importance: "중"},
	}
	// Two stages, neither of them the one the committed table holds, so a
	// row that hard-coded "stage 3" would fail both times.
	deferred := []controls.Deferral{
		{ID: "U-15", Stage: "4", Reason: "needs the deep filesystem walk"},
		{ID: "U-33", Stage: "7", Reason: "needs the deep filesystem walk"},
	}
	set := []controls.Control{
		{ID: "muster.account.root_remote_login", Automation: "auto", References: controls.References{KISA: map[string][]string{"2026": {"U-01"}}}},
	}
	got := render(items, deferred, nil, set, nil)
	for _, want := range []string{
		"| U-15 | 파일 및 디렉터리 소유자 설정 | 상 | — | — | — | deferred (stage 4) |",
		"| U-33 | 숨겨진 파일 및 디렉토리 검색 및 제거 | 하 | — | — | — | deferred (stage 7) |",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing deferred row %q in:\n%s", want, got)
		}
	}
	// The row that is neither enrolled nor deferred keeps saying so, or
	// "deferred" would just be a nicer word for the same gap.
	if !strings.Contains(got, "| U-45 | 메일 서비스 버전 점검 | 중 | — | — | — | not enrolled |") {
		t.Errorf("an item that is neither enrolled nor deferred must still read \"not enrolled\":\n%s", got)
	}
	if !strings.Contains(got, "1 of 4 items enrolled; 1 controls (auto 1, partial 0, manual 0)") {
		t.Errorf("a deferred item must not be counted as enrolled:\n%s", got)
	}
	if strings.Contains(got, "needs the deep filesystem walk") {
		t.Error("the reason belongs in kisa_deferred.json, not in the generated table")
	}
}

// M-3 (spec §11): the report is facts used, not facts collected. One row per
// collector, and a summary line whose three numbers account for every
// registered key.
func TestRenderFactUsageSection(t *testing.T) {
	items := []controls.KISAItem{{ID: "U-01", NameKo: "x", Importance: "상"}}
	usage := []controls.CollectorUsage{
		{Collector: "accounts", Registered: 23, Used: 20, Engine: 1, Unused: []string{"accounts.x", "accounts.y"}},
		{Collector: "walk", Registered: 2, Used: 2, Engine: 0},
	}
	got := render(items, nil, usage, nil, nil)
	if !strings.Contains(got, "\n## Fact keys used by controls\n") {
		t.Errorf("the section heading is missing:\n%s", got)
	}
	for _, want := range []string{
		"22 of 25 registered keys are read by a control (1 by the engine); 2 unused.",
		"| Collector | Registered | Used by a control | Read by the engine | Unused |",
		"| accounts | 23 | 20 | 1 | accounts.x, accounts.y |",
		"| walk | 2 | 2 | 0 | — |",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %q in:\n%s", want, got)
		}
	}
	if strings.Index(got, "| accounts |") > strings.Index(got, "| walk |") {
		t.Error("collector rows must keep the order FactUsage gave them")
	}
}

// B-9: the KISA table says nothing about a control that implements no KISA
// item, so the controls beyond the guide get a table of their own. It states
// what a reviewer needs to judge a check nobody else wrote down: what it
// reads and which STIG rule, if any, it agrees with.
func TestCoverageBeyondTable(t *testing.T) {
	items := []controls.KISAItem{{ID: "U-01", NameKo: "x", Importance: "상"}}
	guideOnly := []controls.Control{
		{ID: "muster.account.root_remote_login", Category: "account", Importance: "상", Automation: "auto",
			References: controls.References{KISA: map[string][]string{"2026": {"U-01"}}}},
	}
	got := render(items, nil, nil, guideOnly, nil)
	if !strings.Contains(got, "\n## Beyond the guide\n") {
		t.Errorf("the section heading is missing:\n%s", got)
	}
	if !strings.Contains(got, "None yet") {
		t.Errorf("a set with no beyond control must say so in one line:\n%s", got)
	}
	if strings.Contains(got, "| Control | Imp. | Automation | Fact keys read | STIG ids | CIS recs |") {
		t.Errorf("an empty section must not render an empty table:\n%s", got)
	}

	withBeyond := append(append([]controls.Control(nil), guideOnly...), controls.Control{
		ID: "muster.beyond.aslr_and_link_protection", Category: "beyond", Importance: "중", Automation: "partial",
		AppliesWhen: []controls.Clause{{Fact: "env.container", Op: "eq", Expected: "none"}},
		Checks: []controls.Clause{
			{Fact: "kernel.sysctl.randomize_va_space", Op: "eq", Expected: 2},
			{Fact: "kernel.sysctl.protected_symlinks", Op: "eq", Expected: 1},
		},
		References: controls.References{STIG: []controls.STIGRef{
			{Benchmark: "rhel9", Version: "V2R4", ID: "RHEL-09-213010"},
			{Benchmark: "ubuntu2204", Version: "V2R3", ID: "UBTU-22-213015"},
		}},
	})
	got = render(items, nil, nil, withBeyond, nil)
	want := "| muster.beyond.aslr_and_link_protection | 중 | partial | env.container, kernel.sysctl.protected_symlinks, kernel.sysctl.randomize_va_space | RHEL-09-213010, UBTU-22-213015 | — |"
	if !strings.Contains(got, want) {
		t.Errorf("missing beyond row\n want %s\n  in:\n%s", want, got)
	}
	if !strings.Contains(got, "| Control | Imp. | Automation | Fact keys read | STIG ids | CIS recs |") {
		t.Errorf("the beyond table needs its header row:\n%s", got)
	}
	if strings.Contains(got, "None yet") {
		t.Errorf("a set with a beyond control must not still say there is none:\n%s", got)
	}
	// A control that implements a KISA item belongs in the table above, not
	// in this one.
	if i := strings.Index(got, "## Beyond the guide"); i >= 0 && strings.Contains(got[i:], "muster.account.root_remote_login") {
		t.Errorf("a guide control must not appear in the beyond table:\n%s", got[i:])
	}
	if render(items, nil, nil, withBeyond, nil) != got {
		t.Error("render must be deterministic")
	}
}

